  final List<ProviderMapItem> _providers;

  ProviderMapRepository({List<ProviderMapItem>? seedProviders})
      : _providers = seedProviders ?? List.from(_defaultProviders);

  @override
  Future<List<ProviderMapItem>> getProviders({ProviderMapFilter? filter}) async {
    if (filter == null) {
      return List.unmodifiable(_providers);
    }
    return _providers.where((item) => filter.matches(item)).toList();
  }

  @override
  Future<ProviderMapItem?> getProviderById(String id) async {
    try {
      return _providers.firstWhere((item) => item.id == id);
    } catch (_) {
      return null;
    }
  }
}
